"""Markdown and self-contained HTML report generation.

No server-side PDF dependency: the HTML report includes print CSS so the browser
can print to PDF.  Reports are stored in SQLite and can be downloaded later.
"""

from __future__ import annotations

import html
import json
import uuid
from datetime import UTC, datetime

from app.analytics import metrics
from app.db import app_db


def _md_table(rows: list[dict], columns: list[str] | None = None, limit: int = 30) -> str:
    if not rows:
        return "_No rows._"
    columns = columns or list(rows[0].keys())
    lines = ["| " + " | ".join(columns) + " |", "|" + "|".join(["---"] * len(columns)) + "|"]
    for row in rows[:limit]:
        lines.append("| " + " | ".join(str(row.get(c, "")) for c in columns) + " |")
    return "\n".join(lines)


def _html_table(rows: list[dict], columns: list[str] | None = None, limit: int = 50) -> str:
    if not rows:
        return "<p><em>No rows.</em></p>"
    columns = columns or list(rows[0].keys())
    head = "".join(f"<th>{html.escape(str(c))}</th>" for c in columns)
    body = []
    for row in rows[:limit]:
        body.append(
            "<tr>"
            + "".join(f"<td>{html.escape(str(row.get(c, '')))}</td>" for c in columns)
            + "</tr>"
        )
    return f"<table><thead><tr>{head}</tr></thead><tbody>{''.join(body)}</tbody></table>"


def _report_html(title: str, markdown_body: str, metadata: dict) -> str:
    # The HTML is intentionally self-contained: inline CSS, no external assets.
    sections = markdown_body.split("\n## ")
    rendered = []
    for index, section in enumerate(sections):
        if index == 0:
            rendered.append(f"<p>{html.escape(section).replace(chr(10), '<br>')}</p>")
            continue
        heading, _, body = section.partition("\n")
        rendered.append(f"<h2>{html.escape(heading)}</h2>")
        rendered.append(
            f"<div class='section-body'>{html.escape(body).replace(chr(10), '<br>')}</div>"
        )
    return f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{html.escape(title)}</title>
<style>
  :root {{ color-scheme: light; }}
  body {{ font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, Arial, sans-serif;
         margin: 0; padding: 32px; color: #17202a; background: #fff; line-height: 1.55; }}
  main {{ max-width: 980px; margin: 0 auto; }}
  h1 {{ font-size: 26px; margin-bottom: 4px; }}
  h2 {{ font-size: 18px; margin-top: 28px; border-bottom: 1px solid #dde3ea; padding-bottom: 6px; }}
  .meta {{ color: #5b6b7c; font-size: 13px; margin-bottom: 24px; }}
  .badge {{ display: inline-block; padding: 2px 8px; border-radius: 999px; background: #eef3f8;
            color: #33475b; font-size: 12px; margin-right: 6px; }}
  table {{ border-collapse: collapse; width: 100%; margin: 12px 0; font-size: 13px; }}
  th, td {{ border: 1px solid #dde3ea; padding: 6px 8px; text-align: left; vertical-align: top; }}
  th {{ background: #f5f8fb; }}
  pre {{ background: #f5f8fb; padding: 12px; overflow-x: auto; font-size: 12px; }}
  .footer {{ margin-top: 40px; color: #5b6b7c; font-size: 12px; border-top: 1px solid #dde3ea;
             padding-top: 12px; }}
  @media print {{ body {{ padding: 0; }} h2 {{ break-after: avoid; }} table {{ break-inside: avoid; }} }}
</style>
</head>
<body>
<main>
<h1>{html.escape(title)}</h1>
<div class="meta">
  <span class="badge">Synthetic dataset</span>
  <span class="badge">Deterministic metrics</span>
  Generated {html.escape(metadata.get("generated_at", ""))}
</div>
{''.join(rendered)}
<div class="footer">
  Generated by the AI Product Analytics Copilot. All metrics are computed in code from the
  synthetic dataset. LLM narration, when enabled, is evidence-checked; it does not compute metrics.
  Use your browser's Print → Save as PDF to export this report.
</div>
</main>
</body>
</html>"""


def create_report(
    title: str,
    question: str | None = None,
    interaction_id: str | None = None,
    query_id: str | None = None,
) -> dict:
    generated_at = datetime.now(UTC).isoformat()
    interaction = app_db.get_ai_interaction(interaction_id) if interaction_id else None
    query = app_db.get_query_history(query_id) if query_id else None
    metadata: dict = {"generated_at": generated_at, "interaction_id": interaction_id, "query_id": query_id}

    parts: list[str] = []
    if question:
        parts.append(f"**Question:** {question}")
    parts.append(f"**Generated:** {generated_at}")

    if interaction:
        parts.append("## Answer")
        parts.append(interaction.get("answer") or "_No answer stored._")
        parts.append("## Evidence")
        try:
            sections = json.loads(interaction.get("sections_json") or "[]")
        except ValueError:
            sections = []
        for section in sections:
            if not isinstance(section, dict):
                continue
            parts.append(f"### {section.get('title', 'Finding')}")
            parts.append(str(section.get("body", "")))
            bullets = section.get("bullets") or []
            if bullets:
                parts.append("\n".join(f"- {b}" for b in bullets))
        parts.append("## Tool calls")
        parts.append(
            _md_table(
                [
                    {
                        "tool": t.get("tool_name"),
                        "status": t.get("status"),
                        "duration_ms": t.get("duration_ms"),
                        "summary": (t.get("result_summary") or "")[:300],
                    }
                    for t in interaction.get("tool_calls", [])
                ]
            )
        )
        if interaction.get("sql_text"):
            parts.append("## Generated SQL")
            parts.append("```sql\n" + interaction["sql_text"] + "\n```")
        parts.append("## Caveats")
        parts.append(
            "- Metrics are deterministic outputs from synthetic data.\n"
            "- Observational associations are not causal claims.\n"
            "- Experiment results should be checked for SRM and practical significance."
        )
    elif query:
        parts.append("## Answer")
        parts.append(query.get("answer") or "_No answer stored._")
        parts.append("## Generated SQL")
        parts.append("```sql\n" + (query.get("generated_sql") or "-- none") + "\n```")
        try:
            preview = json.loads(query.get("result_preview") or "[]")
        except ValueError:
            preview = []
        parts.append("## Result preview")
        parts.append(_md_table(preview))
        parts.append("## Caveats")
        parts.append("Values come directly from the validated SQL result.")
    else:
        overview = metrics.overview()
        parts.append("## KPI snapshot")
        k = overview["kpis"]
        parts.append(
            _md_table(
                [
                    {"metric": "Total users", "value": k["total_users"]},
                    {"metric": "Active users (30d)", "value": k["active_users_30d"]},
                    {"metric": "DAU", "value": k["dau"]},
                    {"metric": "WAU", "value": k["wau"]},
                    {"metric": "MAU", "value": k["mau"]},
                    {"metric": "MRR", "value": k["mrr"]},
                    {"metric": "Purchase conversion", "value": k["purchase_conversion_rate"]},
                    {"metric": "D7 retention", "value": k["retention_d7"]},
                ]
            )
        )
        parts.append("## Channel mix")
        parts.append(_md_table(overview.get("channels", [])))
        parts.append("## Recent anomalies")
        parts.append(_md_table(overview.get("anomalies", [])))

    markdown = f"# {title}\n\n" + "\n\n".join(parts)
    html_body = _report_html(title, markdown, metadata)
    report_id = f"rep_{uuid.uuid4().hex[:12]}"
    record = {
        "id": report_id,
        "title": title,
        "question": question,
        "interaction_id": interaction_id,
        "query_id": query_id,
        "format": "markdown+html",
        "content_md": markdown,
        "content_html": html_body,
        "metadata": metadata,
        "created_at": generated_at,
    }
    app_db.insert_report(record)
    app_db.insert_audit("REPORT_CREATED", {"report_id": report_id, "title": title})
    return record


def get_report(report_id: str) -> dict | None:
    return app_db.get_report(report_id)


def list_reports(limit: int = 50, offset: int = 0) -> list[dict]:
    return app_db.list_reports(limit=limit, offset=offset)
